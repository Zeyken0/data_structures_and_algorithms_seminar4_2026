#pragma once

#include <cstddef>
#include <filesystem>

// Алгоритм однофазной сортировки прямым слиянием.
//
// Используется четыре файла: два исходных f1, f2 и два результирующих g1, g2.
// Отдельной фазы разделения нет: чтение серий из f1 и f2, их слияние и
// попеременная запись результата в g1 или g2 составляют единый проход.
// После прохода файлы меняются ролями (f1 = g1, f2 = g2), повторяется,
// пока не получим файл с одной серией.
//
// input_file — файл с данными, на месте которого после вызова
//              окажется отсортированная последовательность;
// temp_dir   — каталог для вспомогательных файлов (удаляется содержимое
//              созданных им файлов по завершении сортировки);
// run_size   — длина начальных серий. Значение 1 — классическая схема
//              (начальные серии длиной 1); значение больше 1 — ускорение
//              прямого слияния за счёт предварительной сортировки блоков
//              из run_size записей в ОП.
template <typename T>
void one_phase_merge_sort(const std::filesystem::path& input_file,
                          const std::filesystem::path& temp_dir,
                          std::size_t run_size = 1);
