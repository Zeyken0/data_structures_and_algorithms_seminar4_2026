#pragma once

#include <cstddef>
#include <filesystem>

// Алгоритм 2-х фазной сортировки прямым слиянием.
//
// Используется три файла: f (исходный), g и t (вспомогательные).
// Каждый проход состоит из двух фаз:
//   1) фазы разделения — серии из файла f попеременно распределяются
//      по файлам g и t;
//   2) фазы слияния — серии файлов g и t сливается попарно обратно в f,
//      длина серий удваивается.
// Проходы повторяются, пока в файле f не останется одна серия.
//
// input_file — файл с данными, на месте которого после вызова
//              окажется отсортированная последовательность;
// temp_dir   — каталог для вспомогательных файлов (удаляется содержимое
//              созданных им файлов по завершении сортировки);
// run_size   — длина начальных серий. Значение 1 — классическая схема
//              (начальные серии длиной 1); значение больше 1 — ускорение
//              прямого слияния за счёт предварительной сортировки блоков
//              из run_size записей в ОП.
template <typename T>
void two_phase_merge_sort(const std::filesystem::path& input_file,
                          const std::filesystem::path& temp_dir,
                          std::size_t run_size = 1);
