#pragma once

#include <filesystem>

// Алгоритм сортировки естественным слиянием.
//
// Используется три файла: f (исходный) и два вспомогательных — g и t.
// В отличие от прямого слияния длина сливаемых серий не фиксируется:
//series берутся ровно такими, какими их задают данные (максимальные
// неубывающие последовательности), а сливаются два соседних участка.
//
// Каждый проход состоит из двух фаз:
//   1) фазы распределения —series файла f попеременно попадают в g и t;
//   2) фазы слияния —series файлов g и t сливается попарно обратно в f.
// Проходы повторяются, пока в файле f не останется одна серия.
//
// input_file — файл с данными, на месте которого после вызова
//              окажется отсортированная последовательность;
// temp_dir   — каталог для вспомогательных файлов (удаляется содержимое
//              созданных им файлов по завершении сортировки).
template <typename T>
void natural_merge_sort(const std::filesystem::path& input_file,
                        const std::filesystem::path& temp_dir);
